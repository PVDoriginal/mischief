-- $creation
-- Let's start by creating our App and a main Plugin which will serve as the starting point of all our logic.
--
-- @
-- import "Mischief.ECS.Prelude"
--
-- main :: 'IO' ()
-- main = do
--   app <- 'newApp'
--   'addPlugin' \@MainPlugin app
--   'runApp' app
--
-- data MainPlugin
--
-- instance 'Plugin' MainPlugin where
--   init = 'pure' ()
-- @
--
-- You can already run your program and it should work! Although it doesn't do or print anything.

-- $grid
-- The game will play out on a small 2D grid. There are many ways of representing this Mischief, the way I've chosen to do it
-- is by having each tile of the grid be an entity, and the full list of entities stored in a global resource.
--
-- We'll use this @Tile@ component to mark which entities are tiles:
--
-- @
-- data Tile = Tile deriving ('Component')
-- @
--
-- Each tile will also have a @Pos@ component containing it's position on the grid:
--
-- @
-- data Pos = Pos ('Int', 'Int') deriving ('Component')
-- @
--
-- Let's make a resource that stores the list of all tile entities, and call it @Grid@:
--
-- @
-- data Grid = Grid [['Entity']] deriving ('Component')
-- @
--
-- We're also writing these two helper functions returning the width and height of the grid:
--
-- @
-- gridH :: 'Int'
-- gridH = 10
--
-- gridW :: 'Int'
-- gridW = 20
-- @
--
-- Let's write a system that spawns the tiles and initializes the grid resource:
--
-- @
-- spawnGrid :: 'System' ()
-- spawnGrid = do
--   tiles \<-
--     'for' [0 .. gridH - 1] $ \\i -\>
--       'for' [0 .. gridW - 1] $ \\j -\>
--         'spawn' (Tile, Pos (i, j))
--
--   'insertRes' $ Grid tiles
-- @
--
-- @insertRes@ inserts the component as a singleton resource into the ECS. We can grab its value at any time by using @res \@Grid@.
--
-- Now we just need to modify @MainPlugin@ so that it schedules @spawnGrid@ to happen when the app starts.
--
-- @
-- instance 'Plugin' MainPlugin where
--   init = do
--     'systems' spawnGrid
--       & 'schedule' 'Startup'
-- @

-- $traversing
-- Next, we need to code a way for traversing between adjacent tiles. Having a tile entity, we should have easy access to the entities found above, below, to the left and right of it.
--
-- First, I've written this function which gets an entity by position, given the Grid:
--
-- @
-- getTile :: ('Int', 'Int') -> Grid -> 'Maybe' 'Entity'
-- getTile (x, y) (Grid tiles) = do
--   line <- tiles !? x
--   line !? y
-- @
--
-- Now we can write a function that receives the position of a given tile, the grid, and finds tiles offset by a certain amount:
--
-- @
-- moveBy :: ('Int', 'Int') -> Pos -> Grid -> 'Maybe' 'Entity'
-- moveBy (x, y) (Pos (x', y')) = getTile (x' + x, y' + y)
-- @

-- $player
-- Our game needs a player, so we should have a component that uniquely identifies it:
--
-- @
-- data Player = Player deriving ('Component')
-- @
--
-- We should also have a relationship to associate an entity to a tile, teling us that it's currently placed on that tile.
--
-- @
-- data OnTile = OnTile
--
-- instance 'Component' OnTile where
--   type 'IsExclusiveRel' OnTile = 'True'
-- @
--
-- Setting @IsExclusiveRel@ to True on the component instance will make it so there can only be one such relationship on an entity at a time.
-- In our case, this means the player can only be on one tile at a time, and moving them will remove the previous relationship.
--
-- Now it's finally time to spawn our player:
--
-- @
-- spawnPlayer :: 'System' ()
-- spawnPlayer = do
--   'Just' grid \<- res \@Grid
--   'Just' tile \<- getTile (5, 5) grid
--   'void' $ 'spawn' (Player, 'Rel' OnTile tile)
-- @
--
-- @Rel OnTile tile@ inserts the @(OnTile, tile)@ relationship on the player. Tile @(5, 5)@ is just an arbitrary tile I chose to place the player on.
--
-- Now we can schedule the player spawning logic to @Startup@:
--
-- @
-- instance 'Plugin' MainPlugin where
--   init = do
--     'systems' spawnGrid
--       & 'schedule' 'Startup'
--
--     'systems' spawnPlayer
--       & 'schedule' 'Startup'
-- @
--
-- Except there's something really wrong in the logic above!
-- If we run the app, we will get an error pointing us to the @Just grid <-@ in @spawnPlayer@.
-- We are assuming the grid already exists when that system runs, Which means we want
-- to guarantee that @spawnPlayer@ happens /after/ @spawnGrid@.
--
-- We can do this by providing an explicit order when scheduling:
--
-- @
-- instance 'Plugin' MainPlugin where
--   init = do
--     'systems' spawnGrid
--       & 'schedule' 'Startup'
--
--     'systems' spawnPlayer
--       & 'after' spawnGrid
--       & 'schedule' 'Startup'
-- @
--
-- The app should now run without issues!

-- $walls
-- Our game will also have Walls which can block the player's movement. We'll make yet another marker component to represent them:
--
-- @
-- data Wall = Wall deriving ('Component')
-- @
--
-- Let's write a system which spawns a wall on a specific position:
--
-- @
-- spawnWall :: ('Int', 'Int') -> 'System' ('Maybe' 'Entity')
-- spawnWall pos = do
--   'Just' grid \<- 'res' \@Grid
--   'for' (getTile pos grid) $ \tile ->
--     'spawn' (Wall, Rel OnTile tile)
-- @
--
-- And another system that spawns walls on all the tiles at the edge of the grid:
--
-- @
-- spawnWalls :: 'System' ()
-- spawnWalls = do
--   'for_' [0 .. gridW - 1] $ \\i -> spawnWall (0, i)
--   'for_' [0 .. gridW - 1] $ \\i -> spawnWall (gridH - 1, i)
--   'for_' [1 .. gridH - 2] $ \\i -> spawnWall (i, 0)
--   'for_' [1 .. gridH - 2] $ \\i -> spawnWall (i, gridW - 1)
-- @
--
-- The system also needs to be scheduled to run, so @MainPlugin@ now looks like this:
--
-- @
-- instance 'Plugin' MainPlugin where
--   init = do
--     'systems' (spawnGrid, spawnWalls)
--       & 'schedule' 'Startup'
--
--     'systems' spawnPlayer
--       & 'after' spawnGrid
--       & 'schedule' 'Startup'
-- @
--
-- Additionally, it would be helpful to write a system which checks if a given tile has a wall on it:
--
-- @
-- hasWall :: 'Entity' -> 'System' 'Bool'
-- hasWall tile =
--   'not' . 'null' <$> 'query' ['q'|/With Wall, With OnTile -> tile|]
-- @
--
-- We are querying for all entities which have a @Wall@ component and a @OnTile@ relationship to the given entity, and checking whether the list is not null or not.
--
-- But it would be even more useful to have something similar but for any arbitrary component. We can write a generic variant of it like this:
--
-- @
-- tileHas :: forall c. ('Component' c) => 'Entity' -> 'System' 'Bool'
-- tileHas tile = 'not' . 'null' <$> 'query' ['q'|Entity / With (c, OnTile -> tile)|]
-- @
--
-- Make sure to add @{-# LANGUAGE AllowAmbiguousTypes #-}@ at the top of your .hs file, otherwise the type checker will not like that @c@ can not be inferred from the
-- function's input.
--
-- We can now write @hasWall@ as just:
--
-- @
-- hasWall :: 'Entity' -> 'System' 'Bool'
-- hasWall = tileHas \@Wall
-- @

-- $display
-- It's finally time to display our game's grid in the terminal!
--
-- Let's start by writing a system that receives a tile and returns a character to represent it based on what's placed on it:
--
-- @
-- showTile :: 'Entity' -> 'System' 'Char'
-- showTile tile = do
--   player <- tileHas \@Player tile
--   wall <- tileHas \@Wall tile
--
--   'pure' $
--     if
--       | player -> \'@\'
--       | wall -> \'#\'
--       | otherwise -> \'.\'
-- @
--
-- This requires the @MultiWayIf@ language extension, but there are many alternate ways to write it; it's just a personal preference.
--
-- Next, let's write a system which produces a String to represent the whole grid by calling the previous function on each tile:
--
-- @
-- showGrid :: 'System' 'String'
-- showGrid = do
--   'Just' (Grid tiles) <- 'res' \@Grid
--   lines <- 'for' tiles $ 'traverse' showTile
--   'pure' $ 'unlines' lines
-- @
--
-- All that's left is to write a system that prints the string, and schedule it to happen each frame. We'll do the actual
-- printing via the @printClear@ function of "Mischief.ECS.Stdout", which automatically clears the terminal, after each print.
--
-- @
-- printGrid :: 'System' ()
-- printGrid = 'Mischief.ECS.Stdout.printClear' '=<<' showGrid
-- @
--
-- And we need to schedule if, of course.
--
-- @
-- instance 'Plugin' MainPlugin where
--   init = do
--     Stdin.'Mischief.ECS.Stdin.init'
--
--     'systems' (spawnGrid, spawnWalls)
--       & 'schedule' 'Startup'
--
--     'systems' printGrid
--       & 'schedule' 'Update'
-- @
--
-- If you run the app now, you should see the game's grid in your terminal!
--
-- @
-- ####################
-- \#..................#
-- \#..................#
-- \#..................#
-- \#..................#
-- \#....\@.............#
-- \#..................#
-- \#..................#
-- \#..................#
-- ####################
-- @

-- $move
-- Next, we should write a system which moves the player from one tile to another.
--
-- First, let's write the actual logic for moving in a certain direction:
--
-- @
-- movePlayerBy :: ('Int', 'Int') -> 'System' ()
-- movePlayerBy dir = do
--   'Just' grid <- 'res' \@Grid
--   ['q'|OnTile -> (Pos) / With Player|]
--     & 'qmapMaybe' (\\pos -> moveBy dir pos.comp grid)
--     & 'qfilterM' (\\_ newTile -> 'not' <$> hasWall newTile)
--     & 'qinsert' (\\newTile -> 'Rel' OnTile newTile)
--     & 'query_'
-- @
--
-- @qmapMaybe@ /tries/ to get the new tile, after which we run a filter to check if we the tile has a wall on it. Finally we @qmap@ the tile to the new relationship.
-- As you've seen before, @qmap@ automatically runs an insertion of the returned components.

-- $input
-- We also need to somehow get input from the user. Mischief exposes some useful functions for this in the following module:
--
-- @
-- import "Mischief.ECS.Stdin" qualified as Stdin
-- @
--
-- These functions are useful for the purpose of this tutorial but should probably never be used in a released game. Instead, you should import a dedicated
-- haskell input library, or use @mischief-input@ which is based on SDL.
--
-- In order to read input we'll need to add @Stdin.init@ to a plugin, which you'll see a bit later.
--
-- For now, we can just use the @Stdin.readLast@ to empty the input buffer and get the last character typed by the user, if any.
--
-- @
-- movePlayer :: 'System' ()
-- movePlayer = do
--   c <- Stdin.'Mischief.ECS.Stdin.readLast'
--   'for_' c $ \\case
--     \'w\' -> movePlayerBy (-1, 0)
--     \'s\' -> movePlayerBy (1, 0)
--     \'a\' -> movePlayerBy (0, -1)
--     \'d\' -> movePlayerBy (0, 1)
--     _ -> 'pure' ()
-- @
--
-- The @for_@ just \'iterates\' over the @Maybe@, applying the function if it has a value, and doing nothing otherwise.
--
-- At this point the codebase is starting to grow, so I have decided to create a new @PlayerPlugin@ which handles all the player logic (including the new movement system),
-- and make it a dependency of @MainPlugin@:
--
-- @
-- data MainPlugin
--
-- instance 'Plugin' MainPlugin where
--   init = do
--     'systems' (spawnGrid, spawnWalls)
--       & 'schedule' 'Startup'
--
--   deps = ['dep' \@PlayerPlugin]
--
-- data PlayerPlugin
--
-- instance 'Plugin' PlayerPlugin where
--   init = do
--     'systems spawnPlayer
--       & 'after spawnGrid
--       & 'schedule' 'Startup'
--
--     'systems' movePlayer
--       & 'schedule' 'Update'
-- @

-- $rand
-- For some of the next sections, an ability to choose random tiles would be very useful. So let's work on that.
--
-- I've chosen to use the @random@ package, so just add it as a dependency to your project and import it:
--
-- @
-- import System.Random
-- import System.Random.Stateful
-- @
--
-- We need some sort of mutable generator, so I'll create a resource to hold it:
--
-- @
-- data Rand = Rand (IOGenM StdGen) deriving ('Component')
--
-- newGen :: 'System' Rand
-- newGen = Rand \<$\> (newIOGenM =<< initStdGen)
-- @
--
-- Don't forget to insert the resource!
--
-- @
-- instance 'Plugin' MainPlugin where
--   init = do
--     Stdin.'Mischief.ECS.Stdin.init'
--
--     'systems' (spawnGrid, spawnWalls)
--       & 'schedule' 'Startup'
--
--     'systems' printGrid
--       & 'schedule' 'Update'
--
--     'insertRes' =<< newGen
-- @
--
--
-- Now it's possible to write a system that generates a random position on the grid:
--
-- @
-- randomPos :: 'System' ('Int', 'Int')
-- randomPos = do
--   'Just' (Rand gen) <- res @Rand
--   i <- applyIOGen (uniformR (0, gridH - 1)) gen
--   j <- applyIOGen (uniformR (0, gridW - 1)) gen
--   return (i, j)
-- @
--
-- And a system that uses it to get the Entity of a random tile:
--
-- @
-- randomTile :: 'System' 'Entity'
-- randomTile = do
--   'Just' grid <- 'res' \@Grid
--   randomPos <- randomPos
--
--   'pure' . 'unwrap' $ getTile randomPos grid
-- @
--
-- @unwrap@ is a utility function provided by Mischief that just grabs the value out of a @Maybe@, or panics if there is no value. In this case,
-- we know there will be a value since the provided position is valid.

-- $enemies
-- It would be a pretty boring game if there were no obstacles. For that reason, we're going to add some enemies.
--
-- Here's the marker component that will be used to identify them:
--
-- @
-- data Enemy = Enemy deriving ('Component')
-- @
--
-- I'll use this system to spawn an enemy, using the @randomTile@ function defined earlier:
--
-- @
-- spawnEnemy :: 'System' Entity
-- spawnEnemy = do
--   tile <- randomTile
--   'spawn' (Enemy, 'Rel' OnTile tile)
-- @
--
-- And this as a driver to handle all enemy spawning (it just spawns 5 enemies):
--
-- @
-- spawnEnemies :: 'System' ()
-- spawnEnemies = 'for_' [0 .. 4] $ 'const' spawnEnemy
-- @
--
-- I've also modified the @showTile@ system to take enemies into account:
--
-- @
--
-- showTile :: 'Entity' -> 'System' 'Char'
-- showTile tile = do
--   player <- tileHas \@Player tile
--   enemy <- tileHas \@Enemy tile
--   wall <- tileHas \@Wall tile
--
--   'pure' $
--     if
--       | player -> \'@\'
--       | wall -> \'#\'
--       | enemy -> \'!\'
--       | otherwise -> \'.\'
-- @
--
-- Finally, we need a to schedule the enemy spawning, so I've created a new @EnemyPlugin@:
--
-- @
-- data EnemyPlugin
--
-- instance 'Plugin' EnemyPlugin where
--   init = do
--     'systems' spawnEnemies
--       & 'schedule' Startup
-- @
--
-- And added it to the list of plugins added by @MainPlugin@:
--
-- @
-- instance 'Plugin' MainPlugin where
--   init = ...
--
--   deps = ['dep' \@PlayerPlugin, 'dep' \@EnemyPlugin]
-- @
--
-- You should now see something like this when running the app:
--
-- @
-- ####################
-- \#..................#
-- \#..!...............#
-- \#....!.!...........#
-- \#..................#
-- \#....\@.............#
-- \#..................#
-- \#..................#
-- \#........!.!.......#
-- ####################
-- @

-- $moveE
-- Right now the enemies just sit there. Let's make them move!
--
-- Fist, I've written this helper @System@ that receives an enemy's position, the player's position, and decides the direction the enemy will move in.
-- (yes, it technically could be a pure function but you'll see why it's a System a bit later).
--
-- @
-- decideEnemyDir :: Pos -> Pos -> 'System' ('Int', 'Int')
-- decideEnemyDir (Pos (ex, ey)) (Pos (px, py)) = do
--   'pure' $
--     if
--       \| ex \> px -\> (-1, 0)
--       \| ey \> py -\> (0, -1)
--       \| ex \< px -\> (1, 0)
--       \| ey \< py -\> (0, 1)
--       \| otherwise -\> (0, 0)
-- @
--
-- Then, I wrote this system that grabs the player's position and then iterates over all enemies to move them:
--
-- @
-- moveEnemies :: 'System' ()
-- moveEnemies = do
--   'Just' ('From' _ playerPos) \<- 'single' ['q'|OnTile -\> (Pos) / With Player|]
--
--   ['q'|OnTile -> (Pos), Res Grid / With Enemy|]
--     & 'qtraverse' (\\_ (pos, grid) -> (,pos,grid) <$> decideEnemyDir pos.comp playerPos)
--     & 'qmapMaybe' (\\(diff, pos, Res grid) -> moveBy diff pos.comp grid)
--     & 'qinsert' (Rel OnTile)
--     & 'query_'
-- @
--
-- Most of it /should/ be clear to you by now, but let me write some helper comments showing what data is flowing through our query at each point:
--
-- @
-- ['q'|OnTile -> (Pos), Res Grid / With Enemy|]
--   -- Query (From Pos, Res Grid)
--   & 'qtraverse' (\\_ (pos, grid) -> (,pos,grid) <$> decideEnemyDir pos.comp playerPos)
--   -- Query ((Int, Int), From Pos, Res Grid)
--   & 'qmapMaybe' (\\(diff, pos, Res grid) -> moveBy diff pos.comp grid)
--   -- Query (Entity)
--   & 'qinsert' (Rel OnTile)
--   & 'query_'
-- @
--
-- If the lambdas get overwhelming you can always create intermediary functions that work on queries:
--
-- @
-- qdecideEnemyTile :: Pos -> 'Query' 'System' ('From' Pos, 'Res' Grid) -> 'Query' 'System' 'Entity'
-- qdecideEnemyTile playerPos x =
--   x
--     & 'qtraverse' (\\_ (pos, grid) -> (,pos,grid) <$> decideEnemyDir pos.comp playerPos)
--     & 'qmapMaybe' (\\(diff, pos, Res grid) -> moveBy diff pos.comp grid)
-- @
--
-- So our system is now just:
--
-- @
-- moveEnemies :: 'System' ()
-- moveEnemies = do
--   'Just' ('From' _ playerPos) \<- 'single' ['q'|OnTile -\> (Pos) / With Player|]
--
--   ['q'|OnTile -\> (Pos), Res Grid / With Enemy|]
--     & qdecideEnemyTile playerPos
--     & 'qinsert' ('Rel' OnTile)
--     & 'query_'
-- @
--
-- And now to schedule our enemy movement:
--
-- @
-- data EnemyPlugin
--
-- instance 'Plugin' EnemyPlugin where
--   init = do
--     'systems' spawnEnemies
--       & 'schedule' 'Startup'
--
--     'systems' moveEnemies
--       & 'schedule' 'Update'
-- @
--
-- Except there's a small problem. If you run the app now, you may notice you don't see any enemies!
--
-- That's because they all already got to the player and are hiding behind it! We've set @moveEnemies@
-- to happen every frame, and our frames are happening almost instantly. So we need to add some sort of timing to the enemy's movement.
--
-- There are many cleaner high-level solutions to fix this, some of them even using async systems, but instead, I'll take the opportunity to introduce you to an important notion, Time!
--
-- In order to use @Time@ utilities, you need to add the @'TimePlugin'@ to your app, so I'll add it to our @MainPlugin@:
--
-- @
-- deps = ['dep' \@PlayerPlugin, 'dep' \@EnemyPlugin, 'dep' \@TimePlugin]
-- @
--
-- We'll now import the @Time@ module which contains various utlities for keeping track of time, including @Time.delta@ which returns the time, in seconds,
-- that has passed between frames.
--
-- @
-- import "Mischief.ECS.Time" qualified as Time
-- @
--
-- Mischief also provides a handy way of keeping track of time via the @Timer@.
--
-- @
-- import "Mischief.ECS.Timer" ('Mischief.ECS.Timer.Timer')
-- import "Mischief.ECS.Timer" qualified as Timer
-- @
--
-- A Timer is an object that can be ticked down each frame, to trigger certain conditions only once a cerain amount of time has passed.
--
-- Let's create a @Cooldown@ component which stores a Timer.
--
-- @
-- data Cooldown = Cooldown {timer :: 'Mischief.ECS.Timer.Timer'} deriving ('Component')
-- @
--
-- We want this to always be on every Enemy, so we can make it a required component of the @Enemy@ component.
--
-- @
-- instance 'Component' Enemy where
--   'required' = 'require' \@Cooldown
-- @
--
-- In order to have that compile, we also need to provide a @Default@ instance for @Cooldown@:
--
-- @
-- instance 'Default' Cooldown where
--   'def' = Cooldown $ Timer.'Mischief.ECS.Timer.new' 1 Timer.'Mischief.ECS.Timer.Repeat'
-- @
--
-- @Timer.new@ takes a Float (the duration of the timer), and a @Mode@ which is either @Repeat@ or @Once@.
--
-- @Cooldown@ should now automatically be added on every enemy with the default value.
--
-- We can use the @Timer.tick@ function to advance the state of a timer. It returns the new state, along with a Bool that tells us whether the timer has just finished or not.
--
-- All that's left is to put all of this together. I've written this intermediary function to use with queries that will filter the query so that each enemy can only attack when their cooldown has just finished:
--
-- @
-- qfilterCooldown :: 'Query' 'System' a -> 'Query' 'System' a
-- qfilterCooldown x = do
--   x
--     & 'qextend' (,) ['q'|Cooldown|]
--     & 'qfilterM'
--       ( \entity (_, Cooldown timer) -> do
--           delta <- Time.'Mischief.ECS.Time.delta'
--           let (timer', justFinished) = Timer.'Mischief.ECS.Timer.tick' delta timer
--           'insert' (Cooldown timer') entity
--           'pure' justFinished
--       )
--     & 'qmap' 'fst'
-- @
--
-- First we use @qextend@ to also query for the @Cooldown@ of the current entity. Then we run a small impure filter that gets the delta,
-- updates the Timer, modifies the value of Cooldown by re-inserting it on the entity, and filters based on whether the timer had just finished or not.
--
-- We also use a final @qmap@ to get the query back to its original data. This makes it extremely generic!
--
-- Here's the new @moveEnemies@ function, with the timer-based filter:
--
-- @
-- moveEnemies :: 'System' ()
-- moveEnemies = do
--   'Just' ('From' _ playerPos) \<- 'single' ['q'|OnTile -\> (Pos) / With Player|]
--
--   ['q'|OnTile -\> (Pos), Res Grid / With Enemy|]
--     & qfilterCooldown
--     & qdecideEnemyTile playerPos
--     & 'qinsert' ('Rel' OnTile)
--     & 'query_'
-- @
--
-- Mischief's Query system is meant to be extremely modular and easy to generalize. You could probably write a
-- much more generic cooldown filter that works for any component. In fact, such a function is already defined inside the @Timer@ module!
-- Here's how you can use it if you're curious:
--
-- @
-- moveEnemies :: 'System' ()
-- moveEnemies = do
--   'Just' ('From' _ playerPos) \<- 'single' ['q'|OnTile -\> (Pos) / With Player|]
--
--   ['q'|OnTile -\> (Pos), Res Grid / With Enemy|]
--     & Timer.'Mischief.ECS.Timer.qtimer' (.timer) Cooldown
--     & qdecideEnemyTile playerPos
--     & 'qinsert' ('Rel' OnTile)
--     & 'query_'
-- @
